#!/usr/bin/env bash
# 打 Arch Linux 的安装包（.pkg.tar.zst）。CI 用，本地也能跑。
#
#   scripts/package-arch.sh <版本> [输出目录]
#
# 和 package-deb.sh engine 一样：fcitx5 插件 + 设置界面 + 自检工具 + 词库都在一个包里，
# 说明文字、许可证、图标、主题都照 .deb 的那套放（Arch 的路径布局是 /usr/lib、/usr/share）。
#
# 需要 Arch 上的 base-devel cmake extra-cmake-modules fcitx5 alsa-lib zstd libarchive。
# 词库用 scripts/make-data.sh 的产物，默认 dist/data。
#
# 长期安装建议走 AUR 的 wowtype 包（内容与这里一致）；这里的包可以直接 pacman -U。
set -euo pipefail
cd "$(dirname "$0")/.."

VERSION=${1:?用法: package-arch.sh <版本> [输出目录]}
OUT=$(realpath -m "${2:-dist}")
DATA=$(realpath -m "${WOWTYPE_DATA_DIR:-dist/data}")
mkdir -p "$OUT"

for f in lexicon.tsv english.txt words.lm LICENSE SOURCE.txt; do
  [[ -f "$DATA/$f" ]] || { echo "缺 $DATA/$f，先跑 scripts/make-data.sh" >&2; exit 1; }
done

ARCH=$(uname -m)
PKGVER="$VERSION-1"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
stage="$work/stage"
mkdir -p "$stage"

echo "== Rust 核心"
cargo build --release --locked -p wowtype-core

echo "== fcitx5 插件"
cmake -S fcitx5-addon -B "$work/build" -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_INSTALL_PREFIX=/usr -DWOWTYPE_VERSION="$VERSION" >/dev/null
cmake --build "$work/build" -j"$(nproc)"
DESTDIR="$stage" cmake --install "$work/build" >/dev/null
rm -rf "$stage/usr/include"          # 头文件只给开发用

for bin in wowtype-check wowtype-show; do
  install -Dm755 "target/release/$bin" "$stage/usr/bin/$bin"
done

# 词库：雾凇拼音（GPL-3.0）+ WowType 的词级语言模型（CC BY-SA 4.0）
install -d "$stage/usr/share/wowtype"
install -m644 "$DATA"/{lexicon.tsv,english.txt,words.lm} "$stage/usr/share/wowtype/"
install -Dm644 README.md "$stage/usr/share/doc/wowtype/README.md"
install -Dm644 "$DATA/SOURCE.txt" "$stage/usr/share/doc/wowtype/DATA-SOURCE.txt"
[[ -f "$DATA/VERSION" ]] && install -Dm644 "$DATA/VERSION" "$stage/usr/share/doc/wowtype/DATA-VERSION"
install -Dm644 "$DATA/LICENSE" "$stage/usr/share/licenses/wowtype/LICENSE.rime-ice"

# 只 strip ELF（/usr/bin 里还有 Python 写的设置界面 wowtype-config）
is_elf() { [[ "$(head -c4 "$1" | od -An -c | tr -d ' ')" == '177ELF' ]]; }
find "$stage/usr" -type f \( -name '*.so' -o -path '*/bin/*' \) -print0 |
  while IFS= read -r -d '' f; do is_elf "$f" && strip --strip-unneeded "$f"; done

cd "$stage"
SIZE=$(du -sb --apparent-size usr | cut -f1)
{
  echo "# Generated by scripts/package-arch.sh"
  echo "pkgname = wowtype"
  echo "pkgbase = wowtype"
  echo "pkgver = $PKGVER"
  echo "pkgdesc = WeType 风格的拼音输入法：fcitx5 插件 + Rust 引擎（长句、半成品输入、纠错、学习）"
  echo "url = https://github.com/Gloridust/WowType"
  echo "builddate = $(date +%s)"
  echo "packager = WowType CI <noreply@github.com>"
  echo "size = $SIZE"
  echo "arch = $ARCH"
  for lic in MIT Apache-2.0 GPL-3.0-only CC-BY-SA-4.0; do echo "license = $lic"; done
  for dep in fcitx5 alsa-lib gcc-libs; do echo "depend = $dep"; done
  echo "optdepend = python-gobject: 设置界面 wowtype-config"
  echo "optdepend = gtk4: 设置界面"
  echo "optdepend = libadwaita: 设置界面"
  echo "optdepend = noto-fonts-emoji: 候选里的彩色 emoji"
} > .PKGINFO

cat > .INSTALL <<'INSTALL'
post_install() {
  cat <<'EOF'
==> WowType 已安装。
  1) 把 WowType 加进 fcitx5 的输入法列表：wowtype-config --add-to-group
     （或 fcitx5-configtool → 添加「WowType 拼音」）
  2) Ctrl+空格 切到 WowType，输入 nihao 试试。
  设置界面在应用菜单「WowType 设置」。Arch 上没有 im-config，别照 Ubuntu 教程跑它。
EOF
}

post_upgrade() {
  post_install
}
INSTALL

bsdtar -czf .MTREE --format=mtree \
  --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
  .PKGINFO .INSTALL usr

file="$OUT/wowtype-$PKGVER-$ARCH.pkg.tar.zst"
bsdtar -cf - .PKGINFO .INSTALL .MTREE usr | zstd -c -T0 -q -f > "$file"
echo "$file"
